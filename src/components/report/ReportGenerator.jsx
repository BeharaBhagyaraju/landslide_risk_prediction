import React, { useState } from 'react';
import { FileText, Loader2, Download, CloudRain, Droplets, Mountain } from 'lucide-react';
import PropTypes from 'prop-types';
import { jsPDF } from 'jspdf';

const ReportGenerator = ({ riskData, weather, location, historicalProximity }) => {
    const [generating, setGenerating] = useState(false);
    const [showPreview, setShowPreview] = useState(false);

    const handleGenerate = () => {
        setGenerating(true);

        try {
            const doc = new jsPDF();
            const timestamp = new Date().toLocaleString();

            // PDF Header
            doc.setFontSize(22);
            doc.setTextColor(15, 23, 42); // slate-900
            doc.text('LANDSLIDE PREDICTION REPORT', 20, 25);

            doc.setFontSize(10);
            doc.setTextColor(100, 116, 139); // slate-500
            doc.text(`Generated on: ${timestamp}`, 20, 32);
            doc.text(`Coordinates: ${location.lat.toFixed(4)}, ${location.lng.toFixed(4)}`, 20, 37);

            // Risk Assessment Section
            doc.setDrawColor(226, 232, 240); // slate-200
            doc.line(20, 45, 190, 45);

            doc.setFontSize(14);
            doc.setTextColor(15, 23, 42);
            doc.text('1. RISK ASSESSMENT SUMMARY', 20, 55);

            doc.setFontSize(11);
            doc.text(`Current Risk Level: ${riskData?.riskLevel || 'Unknown'}`, 25, 65);
            doc.text(`Overall Risk Score: ${riskData?.overallRisk || 0}%`, 25, 72);

            // Environmental Data Section
            doc.setFontSize(14);
            doc.text('2. ENVIRONMENTAL OBSERVATIONS', 20, 85);

            doc.setFontSize(11);
            doc.text(`7-Day Cumulative Rainfall: ${weather?.total7DayRain || 0}mm`, 25, 95);
            doc.text(`Soil Moisture Saturation: ${riskData?.factors?.soilMoisture || 0}%`, 25, 102);
            doc.text(`Slope Steepness: ${riskData?.factors?.slopeAngle || 0} degrees`, 25, 109);

            // Historical Proximity
            doc.setFontSize(14);
            doc.text('3. HISTORICAL PROXIMITY', 20, 122);
            doc.setFontSize(11);
            if (historicalProximity?.isClose) {
                doc.setTextColor(239, 68, 68); // red-500
                doc.text(`Status: HIGH PROXIMITY ALERT`, 25, 132);
                doc.setTextColor(15, 23, 42);
                doc.text(`Closest Recorded Event: ${historicalProximity.event}`, 25, 139);
                doc.text(`Distance: ${historicalProximity.distance}km`, 25, 146);
            } else {
                doc.setTextColor(34, 197, 94); // green-500
                doc.text('Status: No major historical landslides detected within safety radius.', 25, 132);
            }

            // Footer
            doc.setFontSize(8);
            doc.setTextColor(148, 163, 184); // slate-400
            doc.text('Confidential Disaster Assessment Data - Generated by LandslideWatch AI Platform', 20, 280);

            // Save the PDF
            doc.save(`Landslide_Risk_Report_${location.lat.toFixed(2)}_${location.lng.toFixed(2)}.pdf`);
            setShowPreview(false);
        } catch (error) {
            console.error('PDF Generation Failed:', error);
            alert('Failed to generate PDF. Please try again.');
        } finally {
            setGenerating(false);
        }
    };

    const riskScore = riskData?.overallRisk || 0;
    const rainTotal = weather?.total7DayRain || 0;
    const soilMoisture = riskData?.factors?.soilMoisture || 0;

    return (
        <div className="bg-white p-5 rounded-2xl shadow-sm border border-slate-200">
            <div className="flex items-center gap-3 mb-4">
                <div className="p-2 bg-slate-100 rounded-lg">
                    <FileText className="w-5 h-5 text-slate-600" />
                </div>
                <h3 className="font-semibold text-slate-900 uppercase text-xs tracking-wider">Disaster Reporting</h3>
            </div>

            {!showPreview ? (
                <>
                    <p className="text-xs text-slate-500 mb-4">
                        Generate a localized geotechnical risk report reflecting current climate conditions and historical proximity.
                    </p>
                    <button
                        onClick={() => setShowPreview(true)}
                        className="w-full flex items-center justify-center gap-2 bg-slate-900 text-white py-2.5 rounded-xl text-sm font-medium hover:bg-slate-800 transition-all"
                    >
                        <FileText className="w-4 h-4" />
                        Generate Final Report
                    </button>
                </>
            ) : (
                <div className="space-y-4 animate-in fade-in slide-in-from-bottom-2 duration-300">
                    <div className="p-3 bg-slate-50 rounded-xl border border-slate-100">
                        <div className="text-[10px] font-bold text-slate-400 uppercase mb-2">Report Summary</div>
                        <div className="grid grid-cols-2 gap-3">
                            <div className="flex items-center gap-2">
                                <CloudRain className="w-3.5 h-3.5 text-blue-500" />
                                <span className="text-xs font-medium text-slate-600">{rainTotal}mm Rain</span>
                            </div>
                            <div className="flex items-center gap-2">
                                <Droplets className="w-3.5 h-3.5 text-cyan-500" />
                                <span className="text-xs font-medium text-slate-600">{soilMoisture}% Saturation</span>
                            </div>
                            <div className="flex items-center gap-2">
                                <Mountain className="w-3.5 h-3.5 text-slate-500" />
                                <span className="text-xs font-medium text-slate-600">Slope: {riskData?.factors?.slopeAngle || 0}°</span>
                            </div>
                            <div className="flex items-center gap-2">
                                <div className={`w-2 h-2 rounded-full ${riskScore > 50 ? 'bg-red-500' : 'bg-green-500'}`} />
                                <span className="text-xs font-bold text-slate-900">Risk Index: {riskScore}</span>
                            </div>
                        </div>
                    </div>

                    <div className="flex gap-2">
                        <button
                            onClick={() => setShowPreview(false)}
                            className="flex-1 px-4 py-2 border border-slate-200 text-slate-600 rounded-xl text-sm font-medium hover:bg-slate-50 transition-colors"
                        >
                            Cancel
                        </button>
                        <button
                            onClick={handleGenerate}
                            disabled={generating}
                            className="flex-3 flex items-center justify-center gap-2 bg-blue-600 text-white px-4 py-2 rounded-xl text-sm font-medium hover:bg-blue-700 transition-colors disabled:opacity-50"
                        >
                            {generating ? <Loader2 className="w-4 h-4 animate-spin" /> : <Download className="w-4 h-4" />}
                            {generating ? 'Exporting...' : 'Export PDF'}
                        </button>
                    </div>
                </div>
            )}
        </div>
    );
};

ReportGenerator.propTypes = {
    riskData: PropTypes.object,
    weather: PropTypes.object,
    location: PropTypes.object,
    historicalProximity: PropTypes.object
};

export default ReportGenerator;
